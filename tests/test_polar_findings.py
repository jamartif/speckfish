"""What a real run on an Android project taught (codex on `implement`, 17 minutes, nothing ticked).

1. the agent was told to read a skill that was not installed for it (set up for Claude, run with codex);
2. it said exactly why it stopped ("Blocked: java is unavailable ... T002 needs the phone") and speckfish
   showed only "finished without ticking a single task";
3. a task that needs a physical device kept every chunk from ever finishing.
"""
