# the agent's real final message from that run
POLAR_MESSAGE = (
    "Work stopped at T005. The requested `.agents/skills/speckit-implement/SKILL.md` is missing.\n\n"
    "I created the Gradle Android scaffold and the probe.\n\n"
    "**Blocked:** `gradlew.bat :app:testDebugUnitTest :app:assembleDebug` could not start because Java is "
    "unavailable. Since your checkbox rule requires a successful build, T001–T005 remain unchecked in "
    "`tasks.md`; T002 also needs the intended phone and Flow bond, and T003 depends on that evidence."
)


def _cfg(tmp_path) -> Config:
    return Config(root=tmp_path.resolve())


@pytest.fixture
def check_skills(monkeypatch):
    monkeypatch.delenv("SPECKFISH_SKIP_SKILL_CHECK", raising=False)


# ---------------- 1. the skill the agent is sent to must exist ----------------

def _touch(root: Path, rel: str) -> None:
    f = root / rel
    f.parent.mkdir(parents=True, exist_ok=True)
    f.write_text("x")


@pytest.mark.parametrize("cls,rel", [
    (ClaudeHarness, ".claude/skills/speckit-implement/SKILL.md"),
    (ClaudeHarness, ".claude/commands/speckit.implement.md"),
    (CopilotHarness, ".github/skills/speckit-implement/SKILL.md"),
    (CopilotHarness, ".github/prompts/speckit.implement.prompt.md"),
    (CodexHarness, ".agents/skills/speckit-implement/SKILL.md"),
])
def test_each_agent_finds_its_skill_where_spec_kit_puts_it(tmp_path, cls, rel):
    h = cls(_cfg(tmp_path))
    assert h.has_skill(tmp_path, "speckit-implement") is False
    _touch(tmp_path, rel)
    assert h.has_skill(tmp_path, "speckit-implement") is True


def test_another_agents_skills_do_not_count_and_neither_do_speckfishs_own_commands(tmp_path):
    _touch(tmp_path, ".claude/skills/speckit-implement/SKILL.md")
    _touch(tmp_path, ".claude/commands/spfish-implement.md")        # generated by speckfish, runs speckfish
    assert CodexHarness(_cfg(tmp_path)).has_skill(tmp_path, "speckit-implement") is False
    assert CopilotHarness(_cfg(tmp_path)).has_skill(tmp_path, "speckit-implement") is False
    only_ours = tmp_path / "other"
    _touch(only_ours, ".claude/commands/spfish-implement.md")
    assert ClaudeHarness(_cfg(only_ours)).has_skill(only_ours, "speckit-implement") is False


def test_a_step_is_not_launched_at_a_skill_that_is_missing(tmp_path, check_skills):
    _touch(tmp_path, ".claude/skills/speckit-implement/SKILL.md")   # set up for Claude...
    cfg = _cfg(tmp_path)
    launched = []
    h = CodexHarness(cfg)
    h.build = lambda **k: launched.append(1)                         # ...and run with codex
    with pytest.raises(SystemExit) as e:
        R.run_step(cfg, h, "implement-x", "p", tmp_path, "rid", None, kind="implement", stream=False,
                   progress=False)
    msg = str(e.value)
    assert "codex has no `speckit-implement` skill" in msg and ".agents/skills" in msg
    assert "speckfish init --integration codex" in msg
    assert not launched and not (cfg.runs_dir / "rid").exists()


def test_the_check_does_not_get_in_the_way(tmp_path, check_skills, monkeypatch):
    cfg = _cfg(tmp_path)
    h = CodexHarness(cfg)
    # --dry-run only shows the command: it must work before anything is installed
    res = R.run_step(cfg, h, "plan", "p", tmp_path, "rid", None, kind="plan", dry_run=True)
    assert res.ok and res.error == "dry-run"
    # steps that are not a Spec Kit skill, and agents with no known layout, are never checked
    R.require_skill(h, tmp_path, "review")
    R.require_skill(h, tmp_path, "reconcile")
    R.require_skill(NS(name="fake"), tmp_path, "implement")
    # the switch
    monkeypatch.setenv("SPECKFISH_SKIP_SKILL_CHECK", "1")
    R.require_skill(h, tmp_path, "implement")
    monkeypatch.delenv("SPECKFISH_SKIP_SKILL_CHECK")
    # and once installed it passes
    _touch(tmp_path, ".agents/skills/speckit-implement/SKILL.md")
    R.require_skill(h, tmp_path, "implement")


