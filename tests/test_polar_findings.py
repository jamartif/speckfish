def test_a_blocked_step_says_so_quotes_the_agent_and_tells_what_to_do():
    text = C.summarize(BLOCKED)
    assert text.startswith("BLOCKED  implement-x")
    assert "ERROR  blocked: T001 - Java is unavailable" in text
    assert "fix: do what the agent names" in text and "[MANUAL]" in text
    assert "agent said:" in text and "Work stopped at T005" in text and "T002 also needs the intended phone" in text
    quoted = text.split("agent said:")[1].splitlines()
    assert all(len(line) <= 110 for line in quoted)                         # wrapped, not one 400-char line


def test_a_step_that_failed_for_another_reason_still_says_failed_and_quotes_the_agent():
    text = C.summarize({"ok": False, "step": "plan", "duration_s": 3, "error": "boom", "agent_message": "I gave up."})
    assert text.startswith("FAILED  plan") and "agent said:" in text and "I gave up." in text


def test_a_successful_step_does_not_quote_the_agent():
    assert "agent said" not in C.summarize({"ok": True, "step": "plan", "duration_s": 3, "agent_message": "done"})


def test_a_long_message_is_cut():
    msg = "\n".join(f"line {i}" for i in range(40))
    text = C.summarize({"ok": False, "step": "x", "duration_s": 1, "error": "e", "agent_message": msg})
    assert "line 0" in text and "line 11" in text and "line 20" not in text and "…" in text


def test_the_feature_summary_shows_what_the_agent_and_the_reconcile_said():
    step = {"kind": "implement", "ok": False, "duration_s": 1025, "error_kind": "blocked",
            "agent_message": "BLOCKED: T001 - no JDK", "reconcile_message": "Ticked: none.\nT001's build was not verified."}
    out = {"features": {"001-a": {"state": {"tasks_done": 0, "tasks_total": 41, "tasks_manual": ["T002", "T003"]},
                                  "steps": [step], "stopped": "blocked", "reason": "blocked: T001 - no JDK"}},
           "run_id": "rid"}
    text = C.flow_summary(out)
    assert "001-a  tasks 0/41 (+2 for you)" in text
    assert "BLOCKED implement" in text and "stopped at blocked: blocked: T001 - no JDK" in text
    assert "agent said:" in text and "BLOCKED: T001 - no JDK" in text
    assert "reconcile said:" in text and "T001's build was not verified." in text
    assert C.flow_exit_code({"ok": False, **out, "features": {"001-a": {"stopped": "blocked",
                                                                         "error_kind": "blocked"}}}) == C.EXIT_ENV


