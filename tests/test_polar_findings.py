def test_doctor_says_which_agents_have_their_skills_and_warns_about_the_one_in_use(tmp_path, check_skills):
    (tmp_path / ".specify").mkdir()
    _touch(tmp_path, ".claude/skills/speckit-specify/SKILL.md")
    info = S.do_doctor(_cfg(tmp_path))
    assert info["project"]["skills"] == {"claude": True, "copilot": False, "codex": False}
    info["harness"] = {"harness": "codex", "version": "x", "verified": True}
    text = C.doctor_summary(info)
    assert "Spec Kit skills: claude yes · copilot no · codex no" in text
    assert "WARNING: codex is the agent in use and has no Spec Kit skills here" in text
    assert "speckfish init --integration codex" in text
    info["harness"] = {"harness": "claude", "version": "x", "verified": True}
    assert "WARNING: claude" not in C.doctor_summary(info)


def _console(tmp_path, lines):
    (tmp_path / ".specify").mkdir(exist_ok=True)
    Config(root=tmp_path.resolve()).save()
    calls, it = [], iter(lines)
    asked = []
    shell = SH.Shell(tmp_path, input_fn=lambda p="": (asked.append(p), next(it))[1], out=io.StringIO(),
                     main=lambda argv: calls.append(argv) or 0)
    return shell, calls, asked


def test_switching_to_an_agent_without_skills_offers_to_install_them(tmp_path, check_skills, monkeypatch):
    monkeypatch.setattr(SH.Shell, "installed_agents", lambda self, cfg: ["claude", "codex"])
    shell, calls, asked = _console(tmp_path, ["/harness copilot", "y", "/exit"])
    shell.run()
    assert any("Install them now (speckfish init --integration copilot)?" in a for a in asked)
    assert ["init", "--integration", "copilot"] in [c[-3:] for c in calls]


def test_declining_installs_nothing_and_having_the_skills_asks_nothing(tmp_path, check_skills):
    shell, calls, asked = _console(tmp_path, ["/harness copilot", "n", "/exit"])
    shell.run()
    assert not any(c[-2:-1] == ["init"] or "init" in c for c in calls)
    _touch(tmp_path, ".github/skills/speckit-specify/SKILL.md")
    shell, calls, asked = _console(tmp_path, ["/harness copilot", "/exit"])
    shell.run()
    assert not any("Install them now" in a for a in asked)


