def test_blocked_lines_are_read_from_the_agents_final_message():
    assert W.parse_blocked(POLAR_MESSAGE) == [
        "gradlew.bat :app:testDebugUnitTest :app:assembleDebug` could not start because Java is unavailable. "
        "Since your checkbox rule requires a successful build, T001–T005 remain unchecked in `tasks.md`; "
        "T002 also needs the intended phone and Flow bond, and T003 depends on that evidence."]
    assert W.parse_blocked("BLOCKED: T002 - needs the phone\nblocked: T003 - waits for T002") == [
        "T002 - needs the phone", "T003 - waits for T002"]
    assert W.parse_blocked("- **BLOCKED:** T001 — no JDK") == ["T001 — no JDK"]
    assert W.parse_blocked("nothing was blocked: all done") == []          # the word in a sentence is not a report
    assert W.parse_blocked("") == W.parse_blocked(None) == []              # type: ignore[arg-type]
    assert W.parse_blocked("BLOCKED:") == []


def test_the_chunk_prompt_asks_for_a_blocked_line():
    text = flow.chunk_args([{"id": "T001", "text": "x"}])
    assert "`BLOCKED: <task id> - <the reason>`" in text and "do not tick it" in text


class Talker(ClaudeHarness):
    """A harness whose process prints nothing and whose parsed output carries what the agent 'said'."""
    said = ""

    def build(self, **kw):
        inv = super().build(**kw)
        inv.argv = [sys.executable, "-c", "print('ok')"]
        return inv

    def parse_output(self, stdout, stderr, exit_code):
        return {"result_text": self.said, "text_tail": self.said}


def test_run_step_keeps_the_agents_message_and_its_blocked_lines(tmp_path):
    cfg = _cfg(tmp_path)
    h = Talker(cfg)
    h.said = POLAR_MESSAGE
    res = R.run_step(cfg, h, "implement", "p", tmp_path, "rid", None, stream=False, progress=False,
                     kind="implement")
    assert res.agent_message.startswith("Work stopped at T005") and len(res.blocked) == 1
    assert res.to_dict()["agent_message"] == res.agent_message
    plan = R.run_step(cfg, h, "plan", "p", tmp_path, "rid2", None, stream=False, progress=False, kind="plan")
    assert plan.agent_message and plan.blocked == []                        # only `implement` reports blocked
    h.said = '{"type":"item.completed","item":{}}'
    raw = R.run_step(cfg, h, "plan", "p", tmp_path, "rid3", None, stream=False, progress=False, kind="plan")
    assert raw.agent_message == ""                                          # a tail of raw events is not a message


TASKS = "# Tasks\n- [ ] T001 Bootstrap\n- [ ] T002 Probe on the phone\n"


def _feature(root: Path, text: str = TASKS) -> Path:
    d = root / "specs" / "001-a"
    d.mkdir(parents=True, exist_ok=True)
    for name, body in (("spec.md", "# s"), ("plan.md", "# p"), ("tasks.md", text)):
        (d / name).write_text(body, encoding="utf-8")
    return d


def _chunk_with(monkeypatch, said: str, tick: tuple[str, ...] = ()):
    def do_skill(cfg, skill, args, rid, h, stream, dry, feature=None, step_name=None):
        path = _feature_path / "tasks.md"
        text = path.read_text(encoding="utf-8")
        for t in tick:
            text = text.replace(f"- [ ] {t} ", f"- [x] {t} ")
        path.write_text(text, encoding="utf-8")
        return StepResult(step=step_name, kind="implement", ok=True, exit_code=0, duration_s=1.0,
                          agent_message=said, blocked=W.parse_blocked(said))

    def reconcile(cfg, h, label, prompt, cwd, rid, egm, **k):
        return StepResult(step=label, kind="reconcile", ok=True, exit_code=0, duration_s=1.0,
                          agent_message="Ticked: none. T001's build was not verified.")

    monkeypatch.setattr(S, "do_skill", do_skill)
    monkeypatch.setattr(flow, "run_step", reconcile)


_feature_path: Path


def test_a_chunk_the_agent_could_not_finish_is_blocked_not_just_unticked(tmp_path, monkeypatch):
    global _feature_path
    _feature_path = feat = _feature(tmp_path)
    _chunk_with(monkeypatch, "BLOCKED: T001 - java is not installed\nBLOCKED: T002 - needs the phone")
    res = flow.do_implement_chunk(_cfg(tmp_path), feat, "rid", NS(name="fake"), chunk=5)
    assert res.ok is False and res.error_kind == "blocked"
    assert res.error == "blocked: T001 - java is not installed; T002 - needs the phone"
    assert "build was not verified" in res.reconcile_message              # the reconcile's reasons are kept too


def test_a_chunk_that_ticked_something_is_not_blocked(tmp_path, monkeypatch):
    global _feature_path
    _feature_path = feat = _feature(tmp_path)
    _chunk_with(monkeypatch, "BLOCKED: T002 - needs the phone", tick=("T001",))
    res = flow.do_implement_chunk(_cfg(tmp_path), feat, "rid", NS(name="fake"), chunk=5)
    assert res.ok is True and res.error_kind != "blocked"


def test_the_loop_stops_at_a_blocked_chunk_and_does_not_retry_it(tmp_path, monkeypatch):
    feat = _feature(tmp_path)
    calls = []

    def chunk(*a, **k):
        calls.append(1)
        return StepResult(step="x", kind="implement", ok=False, exit_code=0, duration_s=1.0,
                          error="blocked: T001 - no JDK", error_kind="blocked")

    monkeypatch.setattr(flow, "do_implement_chunk", chunk)
    out = flow.implement_loop(_cfg(tmp_path), feat, "rid", NS(name="fake"))
    assert len(calls) == 1 and out["stopped"] == "blocked" and out["error_kind"] == "blocked"
    assert out["reason"] == "blocked: T001 - no JDK"


# ---------------- 3. tasks that are for a person ----------------

MANUAL_TASKS = """# Tasks
- [x] T001 Bootstrap
- [ ] T002 [MANUAL] Measure first usable HR on the phone
- [ ] T003 (manual) Pin the versions verified by the probe
- [ ] T004 Contracts in src/a.kt
- [ ] T005 [manual] lower case works too
```
- [ ] T099 [MANUAL] inside a code block is an example, not a task
```
"""


def test_manual_tasks_are_recognised_and_never_handed_to_the_agent(tmp_path):
    feat = _feature(tmp_path, MANUAL_TASKS)
    tasks = W.parse_tasks(feat / "tasks.md")
    assert [t["id"] for t in tasks if t["manual"]] == ["T002", "T003", "T005"]
    assert [t["id"] for t in W.next_chunk(tasks, 0)] == ["T004"]
    assert W.open_manual(tasks) == ["T002", "T003", "T005"]
    feat2 = _feature(tmp_path, MANUAL_TASKS.replace("- [ ] T002", "- [x] T002"))
    assert W.open_manual(W.parse_tasks(feat2 / "tasks.md")) == ["T003", "T005"]      # ticked by hand: no longer open


def test_the_loop_finishes_when_only_manual_tasks_are_left_and_says_so(tmp_path, monkeypatch):
    feat = _feature(tmp_path, "# T\n- [x] T001 a\n- [ ] T002 [MANUAL] phone\n- [ ] T003 [MANUAL] pin\n")
    called = []
    monkeypatch.setattr(flow, "do_implement_chunk", lambda *a, **k: called.append(1))
    out = flow.implement_loop(_cfg(tmp_path), feat, "rid", NS(name="fake"))
    assert not called and out["stopped"] is None
    assert out["reason"] == ("the agent's part is done; 2 task(s) marked [MANUAL] are left for you: "
                             "T002, T003")


def test_the_state_and_the_next_step_know_what_is_left_for_you(tmp_path):
    feat = _feature(tmp_path, "# T\n- [x] T001 a\n- [ ] T002 [MANUAL] phone\n")
    cfg = _cfg(tmp_path)
    st = flow.feature_state(cfg, feat)
    assert (st["tasks_done"], st["tasks_total"], st["tasks_pending"], st["tasks_manual"]) == (1, 2, 0, ["T002"])
    st["review"] = {"status": "ok"}
    st.update(review_current=True, blockers=0, majors=0, analyzed=True, drift={"status": "ok"})
    kind, why = flow.next_step(cfg, feat, implement=True, state=st)
    assert kind is None and "except 1 [MANUAL] task(s) left for you: T002" in why
    st["drift"] = None
    assert flow.next_step(cfg, feat, implement=True, state=st)[0] == "drift"     # manual tasks do not hold it back
    st["tasks_pending"] = 3
    assert flow.next_step(cfg, feat, implement=True, state=st) == ("implement", "3 task(s) pending")


